export function getExhibitionTimes(exhibition, date) {
  if (!date) return [];
  const weekday = new Date(date + "T12:00:00").getDay();
  if (exhibition.dates.length) return exhibition.dates.includes(date) ? ["20:00"] : [];
  if (exhibition.sessions.length) return exhibition.sessions.filter(session => session.weekday === weekday).map(session => session.time);
  if (weekday === 1) return [];
  // Example arrival choices within published opening hours.
  return Array.from({length: weekday === 0 || weekday === 6 ? 9 : 8}, (_, i) => String(10 + i).padStart(2, "0") + ":00");
}
